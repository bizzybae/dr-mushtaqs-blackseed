// Helper for size tiers: compareAt is what the size would cost at the
// smallest size’s unit price, so the storefront can show honest savings.
const tiers = (unit, sizes) =>
  sizes.map(([label, qty, priceCents, extra = {}], i) => ({
    label,
    sizeMl: unit === 'mL' ? qty : undefined,
    priceCents,
    compareAtCents: i === 0 ? null : Math.round((sizes[0][2] / sizes[0][1]) * qty),
    default: i === 0,
    ...extra,
  }))

