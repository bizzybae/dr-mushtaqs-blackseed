// Emits idempotent SQL that seeds Supabase from src/data/catalog.js.
//   npm run seed:sql   -> writes supabase/seed.sql
// Apply with the Supabase SQL editor, the MCP `execute_sql` tool, or psql.

import { PRODUCTS, IMAGES, LABEL_BADGES } from '../src/data/catalog.js'

const q = (s) => (s == null ? 'null' : `'${String(s).replace(/'/g, "''")}'`)
const j = (v) => `${q(JSON.stringify(v))}::jsonb`
const arr = (xs) => `array[${xs.map(q).join(',')}]::text[]`

const out = []
out.push('-- Generated by scripts/seed-sql.mjs. Safe to re-run.')
out.push('begin;')

for (const p of PRODUCTS) {
  out.push(`
insert into public.products (slug, name, subtitle, tagline, category, product_type, short_description, long_description, inci_ingredients, is_featured, is_new, is_published, sort_order, badges, specs, seo_title, seo_description)
values (${q(p.slug)}, ${q(p.name)}, ${q(p.subtitle)}, ${q(p.tagline)}, ${q(p.category)}, ${q(p.productType)}, ${q(p.short)}, ${q(p.long)}, ${q(p.ingredients)}, ${p.featured ? 'true' : 'false'}, false, true, ${p.sort}, ${arr(LABEL_BADGES.map((b) => b.key))}, ${j(p.specs)}, ${q(`${p.name} | Dr. Mushtaq’s Blackseed`)}, ${q(p.short)})
on conflict (slug) do update set
  name = excluded.name, subtitle = excluded.subtitle, tagline = excluded.tagline, category = excluded.category,
  product_type = excluded.product_type, short_description = excluded.short_description, long_description = excluded.long_description,
  inci_ingredients = excluded.inci_ingredients, is_featured = excluded.is_featured, is_published = true, sort_order = excluded.sort_order,
  badges = excluded.badges, specs = excluded.specs, seo_title = excluded.seo_title, seo_description = excluded.seo_description, updated_at = now();`)

  // variants
  p.variants.forEach((v, i) => {
    const desc = `${v.format || ''} | ${v.description || ''}`
    out.push(`
insert into public.product_variants (product_id, sku, label, size_ml, price_cents, is_default, sort_order, image_storage_path, description, stock)
select id, ${q(v.sku)}, ${q(v.label)}, ${v.sizeMl ?? 'null'}, ${v.priceCents}, ${v.default ? 'true' : 'false'}, ${i}, ${q(v.image)}, ${q(desc)}, 100
from public.products where slug = ${q(p.slug)}
on conflict (sku) do update set
  product_id = excluded.product_id, label = excluded.label, size_ml = excluded.size_ml, price_cents = excluded.price_cents,
  is_default = excluded.is_default, sort_order = excluded.sort_order, image_storage_path = excluded.image_storage_path, description = excluded.description;`)
  })

  // images: replace set
  out.push(`delete from public.product_images where product_id = (select id from public.products where slug = ${q(p.slug)});`)
  p.gallery.forEach((g, i) => {
    out.push(
      `insert into public.product_images (product_id, storage_path, alt, sort_order, aspect) select id, ${q(g)}, ${q(IMAGES[g]?.alt)}, ${i}, ${IMAGES[g]?.aspect ?? 'null'} from public.products where slug = ${q(p.slug)};`
    )
  })

  // sections: replace set
  out.push(`delete from public.product_sections where product_id = (select id from public.products where slug = ${q(p.slug)});`)
  const sections = [
    ['how_to_use', p.howToUse],
    ['faq', p.faq],
    ['key_points', { safety: p.safety }],
    ['badges', LABEL_BADGES.map((b) => b.key)],
  ]
  sections.forEach(([type, content], i) => {
    out.push(
      `insert into public.product_sections (product_id, section_type, content, sort_order) select id, ${q(type)}, ${j(content)}, ${i} from public.products where slug = ${q(p.slug)};`
    )
  })

  // approved spec claims so the claims table mirrors the label
  out.push(`delete from public.claims where product_id = (select id from public.products where slug = ${q(p.slug)});`)
  const claims = [
    ['Standardized to 4.64% thymoquinone by HPLC', 'spec'],
    ['Cold-pressed below 40 °C, unrefined', 'spec'],
    ['Single-origin Ethiopian Nigella sativa', 'spec'],
    ['Third-party tested, lot number on every unit', 'spec'],
  ]
  claims.forEach(([t, type]) => {
    out.push(
      `insert into public.claims (product_id, text, claim_type, requires_dshea_disclaimer, approved_by, approved_at) select id, ${q(t)}, ${q(type)}, false, 'founder', now() from public.products where slug = ${q(p.slug)};`
    )
  })
}

// one published collection containing all five
out.push(`
insert into public.collections (slug, name, description, hero_image_url, sort_order, is_published)
values ('the-five', 'The Five', 'Every Dr. Mushtaq’s product, each built on the same single-origin, 4.64% thymoquinone oil.', 'collection-flatlay', 0, true)
on conflict (slug) do update set name = excluded.name, description = excluded.description, hero_image_url = excluded.hero_image_url, is_published = true;
delete from public.collection_products where collection_id = (select id from public.collections where slug = 'the-five');
insert into public.collection_products (collection_id, product_id, sort_order)
select c.id, p.id, p.sort_order from public.collections c cross join public.products p where c.slug = 'the-five';`)

// retire anything that is not one of the five
out.push(`update public.products set is_published = false where slug not in (${PRODUCTS.map((p) => q(p.slug)).join(',')});`)

out.push('commit;')
process.stdout.write(out.join('\n') + '\n')
